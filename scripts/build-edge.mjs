import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../line-registration');
const read=file=>fs.readFileSync(path.join(root,file),'utf8').replace(/\r\n/g,'\n');
const result='// @ts-nocheck\n// Generated by scripts/build-edge.mjs; do not edit directly.\n'+read('delivery.mjs').replace(/^export /gm,'')+'\n'+read('schedule.js')+'\n'+read('security.js')+'\n'+read('server.mjs').replace(/^import .*;\n/gm,'').replace(/^export /gm,'')+'\nDeno.serve(createHandler(Deno.env.toObject()));\n';
if(process.argv.includes('--check')){
 if(read('index.ts')!==result)throw Error('Edge bundle is stale: run node scripts/build-edge.mjs');
}else fs.writeFileSync(path.join(root,'index.ts'),result);
